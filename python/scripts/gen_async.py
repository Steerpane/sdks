"""Generate src/steerpane/_async_client.py from _client.py. Run after editing _client.py; a test fails if they drift.

Plain text rules rather than a separate async source: the two clients have the same methods, so only the I/O words differ.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src" / "steerpane"
CLASSES = ["Actions", "Sessions", "Profiles", "Runs", "Files", "Embeds", "Webhooks", "Vault", "Crawls", "Mcp", "Steerpane"]
SYNC_HELPERS = {"_clean", "_seg", "_retry_after", "_parse", "_resolve_config", "_rate_limited", "__init__", "__repr__"}
KEEP_FROM_SYNC = ["_clean", "_seg", "_retry_after", "_parse", "_resolve_config", "_rate_limited", "ENDED_SESSION_STATUSES", "ENDED_RUN_STATUSES", "ENDED_CRAWL_STATUSES",
                  "RETRY_STATUSES", "MCP_PROTOCOL", "StrList", "DictList"]


def generate() -> str:
    text = (SRC / "_client.py").read_text(encoding="utf-8")
    start = text.index("class Actions:")
    end = text.index("def _rate_limited(")
    body = text[start:end].rstrip() + "\n"

    def asyncify_def(match: re.Match[str]) -> str:
        return match.group(0) if match.group(2) in SYNC_HELPERS else f"{match.group(1)}async def {match.group(2)}"

    body = re.sub(r"^(\s*)def (\w+)", asyncify_def, body, flags=re.M)
    body = body.replace("time.sleep(", "await asyncio.sleep(")
    body = re.sub(r"(?<![\w.])self\._c\.request\(", "await self._c.request(", body)
    body = body.replace("self._c.request_bytes(", "await self._c.request_bytes(")
    body = body.replace("self._c.raw_request(", "await self._c.raw_request(")
    body = re.sub(r"= self\.(get|_post)\(", r"= await self.\1(", body)
    body = re.sub(r"^(\s*)self\.(_post|_ensure_session)\(", r"\1await self.\2(", body, flags=re.M)
    body = re.sub(r"\breturn self\._post\(", "return await self._post(", body)
    body = body.replace("return self.run(", "return await self.run(")
    body = body.replace('self._post("tools/list", {})["tools"]', '(await self._post("tools/list", {}))["tools"]').replace("await (await", "(await")
    body = body.replace("response = self._http.request(", "response = await self._http.request(")
    body = body.replace("response = self.raw_request(", "response = await self.raw_request(")
    body = re.sub(r"return self\.(request|raw_request)\(", r"return await self.\1(", body)
    body = body.replace("self._http.close()", "await self._http.aclose()")
    body = body.replace("httpx.Client", "httpx.AsyncClient")
    body = body.replace("async def __enter__", "async def __aenter__").replace("async def __exit__", "async def __aexit__")
    body = body.replace("await self.close()", "await self.aclose()").replace("self.close()", "await self.aclose()")
    body = body.replace("async def close(", "async def aclose(")
    body = body.replace("Iterator[Any]", "AsyncIterator[Any]")
    body = body.replace("page = list_call(cursor=cursor, **params)", "page = await list_call(cursor=cursor, **params)")
    body = re.sub(r'^(\s*)(for s in client\.paginate)', r"\1async \2", body, flags=re.M)
    body = body.replace('`for s in client.paginate', '`async for s in client.paginate')
    for name in CLASSES:
        prefix = "Async" if name == "Steerpane" else "_Async"
        body = re.sub(rf"\b{name}\b(?!-)", prefix + name, body)
    body = body.replace("steerpane-sdk-python", "steerpane-sdk-python-async")
    header = (
        '"""GENERATED by scripts/gen_async.py from _client.py. Do not edit."""\n'
        "from __future__ import annotations\n\n"
        "import asyncio\nimport json\nimport time\nimport uuid\nfrom collections.abc import AsyncIterator, Callable\nfrom pathlib import Path\nfrom typing import Any\n\n"
        "import httpx\n\n"
        "from ._client import " + ", ".join(sorted(KEEP_FROM_SYNC)) + "\n"
        "from ._version import __version__\n"
        "from .errors import SteerpaneError, ToolError, from_response\n"
        "from .types import AgentRun, Capture, Credential, CrawlJob, EmbedLink, FetchResult, HumanResult, Page, Profile, SearchResponse, Session, StoredFile, UploadUrl, Webhook\n\n\n"
    )
    return header + body


def main() -> int:
    target = SRC / "_async_client.py"
    out = generate()
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != out:
            print("_async_client.py is out of date: run scripts/gen_async.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(out, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
